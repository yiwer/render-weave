import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const dir=process.argv[2];
const text=await readFile(join(dir,'review.html'),'utf8');
const requirement=await readFile(join(dir,'round-copy/requirement.md'));
const escape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
assert.ok(text.includes(escape(requirement.toString('utf8'))),'单页必须直接显示封存修改要求全文');
assert.ok(text.includes('round-copy/requirement.md'),'单页必须链接封存原文');
assert.ok(text.includes(createHash('sha256').update(requirement).digest('hex')),'单页必须给出要求SHA');
assert.ok(text.indexOf('修改要求优先')<text.indexOf('<h2>原图</h2>'),'优先级说明必须在图片前可见');
const table=JSON.parse(await readFile(join(dir,'review-template.json')));
assert.equal(table.items.length,16);
assert.ok(table.items.every(i=>i.decision===null));
assert.equal(table.activeMinutes,null);
assert.equal(table.businessAcceptance,null);
assert.match(table.items.find(i=>i.id==='Z10').reviewBasis,/最后一格.*底边齐平/);
assert.match(table.items.find(i=>i.id==='Z12').reviewBasis,/两端.*字间距相同/);
assert.ok(table.items.filter(i=>!['Z10','Z12'].includes(i.id)).every(i=>i.reviewBasis.includes('修改前')));
assert.ok(text.includes('修改前基准图'));
console.log(JSON.stringify({passed:true,directory:dir,items:16,requirementSha256:createHash('sha256').update(requirement).digest('hex')}));
