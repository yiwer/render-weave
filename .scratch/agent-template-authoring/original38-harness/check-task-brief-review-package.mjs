import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const dir=process.argv[2];
const page=await readFile(join(dir,'review.html'),'utf8');
const brief=await readFile(join(dir,'round-copy/agent/docs/brief.md'));
const sha=createHash('sha256').update(brief).digest('hex');
const escape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
assert.ok(page.includes(escape(brief.toString('utf8'))),'单页必须直接显示封存业务说明全文');
assert.ok(page.includes('round-copy/agent/docs/brief.md'),'单页必须链接封存业务说明');
assert.ok(page.includes(sha),'单页必须展示业务说明SHA');
assert.ok(page.indexOf('业务说明优先')<page.indexOf('<h2>原图</h2>'),'图片前必须说明业务输入优先级');
const review=JSON.parse(await readFile(join(dir,'review-template.json')));
assert.equal(review.taskBrief.sha256,sha);
assert.equal(review.items.length,16);
assert.ok(review.items.every(i=>i.decision===null));
assert.equal(review.activeMinutes,null);
assert.equal(review.businessAcceptance,null);
const z11=review.items.find(i=>i.id==='Z11');
assert.match(z11.reviewBasis,/蓝色.*数字.*不画/);
assert.match(z11.reviewBasis,/其他设施图标/);
assert.equal(z11.briefSha256,sha);
const scope=await readFile(join(dir,'scope.md'),'utf8');
assert.match(scope,/\| Z11 \|[^\n]*不画/);
const round=JSON.parse(await readFile(join(dir,'round-copy/round.json')));
if(round.task==='template-revision')assert.ok(page.includes('不据业务说明扩增本轮修改范围'));
console.log(JSON.stringify({passed:true,directory:dir,items:16,briefSha256:sha}));
